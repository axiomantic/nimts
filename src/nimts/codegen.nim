type
  TsParam* = object
    name*: string
    nimType*: string
    tsType*: string

  TsTypeField* = object
    name*: string
    tsType*: string

  TsProc* = object
    name*: string
    cabiName*: string
    params*: seq[TsParam]
    returnNimType*: string
    returnTsType*: string
    isAsync*: bool
    isHandleReturn*: bool
    returnKind*: string # "void", "primitive", "string", "bytes", "handle", "object", "promise"

  TsType* = object
    name*: string
    isHandle*: bool
    fields*: seq[TsTypeField]

  TsModuleMeta* = object
    name*: string
    wasmFileName*: string
    types*: seq[TsType]
    procs*: seq[TsProc]

proc mapNimTypeToTs*(nimType: string): string =
  let t = nimType.strip
  case t
  of "int", "int32", "int16", "int8", "uint", "uint32", "uint16", "uint8", "float", "float32", "float64", "csize_t":
    return "number"
  of "int64", "uint64":
    return "bigint"
  of "bool":
    return "boolean"
  of "string", "cstring", "char":
    return "string"
  of "seq[byte]", "openArray[byte]", "seq[uint8]", "openArray[uint8]":
    return "Uint8Array"
  of "void", "":
    return "void"
  else:
    if t.startsWith("Future[") and t.endsWith("]"):
      let inner = t[7 .. ^2]
      return "Promise<" & mapNimTypeToTs(inner) & ">"
    if t.startsWith("Option[") and t.endsWith("]"):
      let inner = t[7 .. ^2]
      return mapNimTypeToTs(inner) & " | null"
    if t.startsWith("seq[") and t.endsWith("]"):
      let inner = t[4 .. ^2]
      return mapNimTypeToTs(inner) & "[]"
    if t.startsWith("NimTsHandle[") and t.endsWith("]"):
      let inner = t[12 .. ^2]
      return inner
    if t.startsWith("NimTsIterator[") and t.endsWith("]"):
      let inner = t[14 .. ^2]
      return "NimTsIterator<" & mapNimTypeToTs(inner) & ">"
    if t.startsWith("NimTsChannel[") and t.endsWith("]"):
      let inner = t[13 .. ^2]
      return "NimTsChannel<" & mapNimTypeToTs(inner) & ">"
    if t.startsWith("Channel[") and t.endsWith("]"):
      let inner = t[8 .. ^2]
      return "NimTsChannel<" & mapNimTypeToTs(inner) & ">"
    if t == "Channel" or t == "NimTsChannel":
      return "NimTsChannel<any>"
    return t

proc generateDts*(meta: TsModuleMeta): string =
  var lines: seq[string] = @[]
  lines.add("// " & meta.name & ".d.ts - Generated by nimts (TypeScript / WASM)")
  lines.add("// Do not edit directly.")
  lines.add("")
  lines.add("export interface NimTsOptions {")
  lines.add("  wasmPath?: string | URL;")
  lines.add("  wasmModule?: WebAssembly.Module;")
  lines.add("  wasmBytes?: BufferSource;")
  lines.add("  wasmInstance?: WebAssembly.Instance;")
  lines.add("  imports?: WebAssembly.Imports;")
  lines.add("}")
  lines.add("")
  lines.add("export declare class NimTsIterator<T> implements IterableIterator<T> {")
  lines.add("  readonly handleId: number;")
  lines.add("  constructor(handleId: number);")
  lines.add("  next(): IteratorResult<T, undefined>;")
  lines.add("  return(): IteratorResult<T, undefined>;")
  lines.add("  dispose(): void;")
  lines.add("  [Symbol.iterator](): IterableIterator<T>;")
  lines.add("}")
  lines.add("")
  lines.add("export declare class NimTsChannel<T> implements AsyncIterable<T> {")
  lines.add("  readonly channelId: number;")
  lines.add("  constructor(channelId: number);")
  lines.add("  next(): Promise<IteratorResult<T, undefined>>;")
  lines.add("  return(): Promise<IteratorResult<T, undefined>>;")
  lines.add("  close(): void;")
  lines.add("  send(item: T): boolean;")
  lines.add("  [Symbol.asyncIterator](): AsyncIterator<T>;")
  lines.add("}")
  lines.add("")
  lines.add("export type Channel<T> = NimTsChannel<T>;")
  lines.add("")

  # Emit handle classes or interfaces
  for typ in meta.types:
    if typ.isHandle:
      lines.add("export declare class " & typ.name & " {")
      lines.add("  readonly handleId: number;")
      lines.add("  constructor(handleId: number);")
      lines.add("  dispose(): void;")
      lines.add("}")
    else:
      lines.add("export interface " & typ.name & " {")
      if typ.fields.len > 0:
        for f in typ.fields:
          lines.add("  " & f.name & ": " & f.tsType & ";")
      else:
        lines.add("  [key: string]: any;")
      lines.add("}")
    lines.add("")

  # Emit Exports interface
  lines.add("export interface " & meta.name & "Exports {")
  var seenInterfaceSigs = initHashSet[string]()
  for p in meta.procs:
    let paramSigs = p.params.mapIt(it.name & ": " & it.tsType).join(", ")
    let retSig = if p.isAsync and not p.returnTsType.startsWith("Promise<"):
      "Promise<" & p.returnTsType & ">"
    else:
      p.returnTsType
    let sigKey = p.name & "(" & paramSigs & "): " & retSig
    if not seenInterfaceSigs.contains(sigKey):
      seenInterfaceSigs.incl(sigKey)
      lines.add("  " & p.name & "(" & paramSigs & "): " & retSig & ";")
  lines.add("}")
  lines.add("")

  # Lifecycle methods
  lines.add("export declare function initNimTs(options?: NimTsOptions): Promise<" & meta.name & "Exports>;")
  lines.add("export declare function initNimTsSync(options: NimTsOptions): " & meta.name & "Exports;")
  lines.add("export declare function getNimTs(): " & meta.name & "Exports;")
  lines.add("export declare function getNimTsModule(): any;")
  lines.add("export declare function isInitialized(): boolean;")
  lines.add("")

  # Top-level functions
  var seenTopLevelSigs = initHashSet[string]()
  for p in meta.procs:
    let paramSigs = p.params.mapIt(it.name & ": " & it.tsType).join(", ")
    let retSig = if p.isAsync and not p.returnTsType.startsWith("Promise<"):
      "Promise<" & p.returnTsType & ">"
    else:
      p.returnTsType
    let sigKey = p.name & "(" & paramSigs & "): " & retSig
    if not seenTopLevelSigs.contains(sigKey):
      seenTopLevelSigs.incl(sigKey)
      lines.add("export declare function " & p.name & "(" & paramSigs & "): " & retSig & ";")

  result = lines.join("\n") & "\n"

proc generateProcBody(p: TsProc, fnName: string, isExported: bool, meta: TsModuleMeta): seq[string] =
  var lines: seq[string] = @[]
  let paramNames = p.params.mapIt(it.name).join(", ")
  let exportPrefix = if isExported: "export " else: ""
  let asyncPrefix = if p.isAsync: "async " else: ""
  lines.add(exportPrefix & asyncPrefix & "function " & fnName & "(" & paramNames & ") {")
  lines.add("  _assertInit();")

  var callArgs: seq[string] = @[]
  var allocStmts: seq[string] = @[]
  var freeStmts: seq[string] = @[]

  for param in p.params:
    case param.tsType
    of "string":
      let varName = "_" & param.name & "_buf"
      allocStmts.add("  const " & varName & " = _allocString(" & param.name & ");")
      callArgs.add(varName & ".ptr")
      callArgs.add(varName & ".len")
      freeStmts.add("  _free(" & varName & ".ptr);")
    of "Uint8Array":
      let varName = "_" & param.name & "_buf"
      allocStmts.add("  const " & varName & " = _allocBytes(" & param.name & ");")
      callArgs.add(varName & ".ptr")
      callArgs.add(varName & ".len")
      freeStmts.add("  _free(" & varName & ".ptr);")
    of "number", "boolean", "bigint":
      callArgs.add(param.name)
    else:
      if param.nimType.contains("Handle") or meta.types.anyIt(it.name == param.tsType and it.isHandle):
        callArgs.add(param.name & ".handleId")
      else:
        let varName = "_" & param.name & "_buf"
        allocStmts.add("  const " & varName & " = _allocString(JSON.stringify(" & param.name & "));")
        callArgs.add(varName & ".ptr")
        callArgs.add(varName & ".len")
        freeStmts.add("  _free(" & varName & ".ptr);")

  for a in allocStmts: lines.add(a)
  lines.add("  try {")
  let rawCall = "_exports." & p.cabiName & "(" & callArgs.join(", ") & ")"

  if p.isAsync:
    lines.add("    const promiseId = " & rawCall & ";")
    lines.add("    return new Promise((resolve, reject) => {")
    lines.add("      if (_settledEarly.has(promiseId)) {")
    lines.add("        const early = _settledEarly.get(promiseId);")
    lines.add("        _settledEarly.delete(promiseId);")
    lines.add("        if (early.isError) reject(new Error(early.errorMsg));")
    lines.add("        else {")
    lines.add("          resolve(_resolveValue(early.bytes, early.bytes ? early.bytes.length : 0, " & "\"" & p.returnKind & "\"" & "));")
    lines.add("        }")
    lines.add("      } else {")
    lines.add("        _pendingPromises.set(promiseId, { resolve, reject, kind: " & "\"" & p.returnKind & "\"" & " });")
    lines.add("      }")
    lines.add("    });")
  else:
    if p.returnKind == "void":
      lines.add("    " & rawCall & ";")
      lines.add("    return;")
    elif p.returnKind in ["int32", "primitive"]:
      if p.returnTsType == "boolean":
        lines.add("    return Boolean(" & rawCall & ");")
      else:
        lines.add("    return " & rawCall & ";")
    elif p.returnKind in ["int64", "float32", "float64"]:
      lines.add("    return " & rawCall & ";")
    elif p.returnKind == "bool":
      lines.add("    return Boolean(" & rawCall & ");")
    elif p.returnKind == "char":
      lines.add("    return String.fromCharCode(" & rawCall & ");")
    elif p.returnKind == "string":
      lines.add("    const packed = " & rawCall & ";")
      lines.add("    const { ptr, len } = _unpackResult64(packed);")
      lines.add("    const str = _readString(ptr, len);")
      lines.add("    _free(ptr);")
      lines.add("    return str;")
    elif p.returnKind == "bytes":
      lines.add("    const packed = " & rawCall & ";")
      lines.add("    const { ptr, len } = _unpackResult64(packed);")
      lines.add("    const bytes = _readBytes(ptr, len);")
      lines.add("    _free(ptr);")
      lines.add("    return bytes;")
    elif p.returnKind == "handle":
      lines.add("    const handleId = " & rawCall & ";")
      lines.add("    return new " & p.returnTsType & "(handleId);")
    elif p.returnKind.startsWith("iterator:"):
      let k = p.returnKind[9 .. ^1]
      lines.add("    const handleId = " & rawCall & ";")
      lines.add("    return new NimTsIterator(handleId, \"" & k & "\");")
    elif p.returnKind == "iterator":
      lines.add("    const handleId = " & rawCall & ";")
      lines.add("    return new NimTsIterator(handleId, \"primitive\");")
    elif p.returnKind.startsWith("channel:"):
      let k = p.returnKind[8 .. ^1]
      lines.add("    const channelId = " & rawCall & ";")
      lines.add("    return new NimTsChannel(channelId, \"" & k & "\");")
    elif p.returnKind == "channel":
      lines.add("    const channelId = " & rawCall & ";")
      lines.add("    return new NimTsChannel(channelId, \"primitive\");")
    elif p.returnKind == "object":
      lines.add("    const packed = " & rawCall & ";")
      lines.add("    const { ptr, len } = _unpackResult64(packed);")
      lines.add("    const jsonStr = _readString(ptr, len);")
      lines.add("    _free(ptr);")
      lines.add("    return JSON.parse(jsonStr);")
    else:
      lines.add("    return " & rawCall & ";")

  lines.add("  } finally {")
  for f in freeStmts: lines.add(f)
  lines.add("  }")
  lines.add("}")
  lines.add("")
  return lines

proc generateJs*(meta: TsModuleMeta, relativeWasmPath: string = ""): string =
  let wasmPath = if relativeWasmPath.len > 0: relativeWasmPath else: "./" & meta.wasmFileName
  var lines: seq[string] = @[]
  lines.add("// " & meta.name & ".js - Generated by nimts (TypeScript / WASM)")
  lines.add("// Do not edit directly.")
  lines.add("")
  lines.add("let _runtime = null;")
  lines.add("let _exports = null;")
  lines.add("let _memory = null;")
  lines.add("let _initialized = false;")
  lines.add("const _textDecoder = typeof TextDecoder !== 'undefined' ? new TextDecoder('utf-8') : null;")
  lines.add("const _textEncoder = typeof TextEncoder !== 'undefined' ? new TextEncoder() : null;")
  lines.add("")
  lines.add("function _utf8Decode(bytes) {")
  lines.add("  let str = '';")
  lines.add("  let i = 0;")
  lines.add("  while (i < bytes.length) {")
  lines.add("    const b1 = bytes[i++];")
  lines.add("    if (b1 < 0x80) {")
  lines.add("      str += String.fromCharCode(b1);")
  lines.add("    } else if (b1 > 0xbf && b1 < 0xe0) {")
  lines.add("      const b2 = bytes[i++];")
  lines.add("      str += String.fromCharCode(((b1 & 0x1f) << 6) | (b2 & 0x3f));")
  lines.add("    } else if (b1 > 0xdf && b1 < 0xf0) {")
  lines.add("      const b2 = bytes[i++];")
  lines.add("      const b3 = bytes[i++];")
  lines.add("      str += String.fromCharCode(((b1 & 0x0f) << 12) | ((b2 & 0x3f) << 6) | (b3 & 0x3f));")
  lines.add("    } else {")
  lines.add("      const b2 = bytes[i++];")
  lines.add("      const b3 = bytes[i++];")
  lines.add("      const b4 = bytes[i++];")
  lines.add("      let cp = ((b1 & 0x07) << 18) | ((b2 & 0x3f) << 12) | ((b3 & 0x3f) << 6) | (b4 & 0x3f);")
  lines.add("      cp -= 0x10000;")
  lines.add("      str += String.fromCharCode((cp >> 10) + 0xd800, (cp & 0x3ff) + 0xdc00);")
  lines.add("    }")
  lines.add("  }")
  lines.add("  return str;")
  lines.add("}")
  lines.add("")
  lines.add("function _utf8Encode(str) {")
  lines.add("  const bytes = [];")
  lines.add("  for (let i = 0; i < str.length; i++) {")
  lines.add("    let cp = str.charCodeAt(i);")
  lines.add("    if (cp >= 0xd800 && cp <= 0xdbff && i + 1 < str.length) {")
  lines.add("      const next = str.charCodeAt(i + 1);")
  lines.add("      if (next >= 0xdc00 && next <= 0xdfff) {")
  lines.add("        cp = 0x10000 + ((cp - 0xd800) << 10) + (next - 0xdc00);")
  lines.add("        i++;")
  lines.add("      }")
  lines.add("    }")
  lines.add("    if (cp < 0x80) {")
  lines.add("      bytes.push(cp);")
  lines.add("    } else if (cp < 0x800) {")
  lines.add("      bytes.push(0xc0 | (cp >> 6), 0x80 | (cp & 0x3f));")
  lines.add("    } else if (cp < 0x10000) {")
  lines.add("      bytes.push(0xe0 | (cp >> 12), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f));")
  lines.add("    } else {")
  lines.add("      bytes.push(0xf0 | (cp >> 18), 0x80 | ((cp >> 12) & 0x3f), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f));")
  lines.add("    }")
  lines.add("  }")
  lines.add("  return new Uint8Array(bytes);")
  lines.add("}")
  lines.add("")
  lines.add("const _pendingPromises = new Map();")
  lines.add("const _settledEarly = new Map();")
  lines.add("const _finalizer = typeof FinalizationRegistry !== 'undefined' ? new FinalizationRegistry(h => {")
  lines.add("  if (_exports && _exports.nimts_destroy_handle) _exports.nimts_destroy_handle(h);")
  lines.add("}) : null;")
  lines.add("")
  lines.add("function _assertInit() {")
  lines.add("  if (!_initialized) throw new Error(\"nimts module '" & meta.name & "' not initialized. Await initNimTs() first.\");")
  lines.add("}")
  lines.add("")
  lines.add("function _getBuffer() {")
  lines.add("  if (!_memory) _assertInit();")
  lines.add("  return _memory.buffer;")
  lines.add("}")
  lines.add("")
  lines.add("function _readString(ptr, len) {")
  lines.add("  if (!ptr || len <= 0) return '';")
  lines.add("  const bytes = new Uint8Array(_getBuffer(), ptr, len);")
  lines.add("  return _textDecoder ? _textDecoder.decode(bytes) : _utf8Decode(bytes);")
  lines.add("}")
  lines.add("")
  lines.add("function _readBytes(ptr, len) {")
  lines.add("  if (!ptr || len <= 0) return new Uint8Array(0);")
  lines.add("  return new Uint8Array(_getBuffer(), ptr, len).slice();")
  lines.add("}")
  lines.add("")
  lines.add("function _allocString(str) {")
  lines.add("  if (typeof str !== 'string') str = String(str);")
  lines.add("  const encoded = _textEncoder ? _textEncoder.encode(str) : _utf8Encode(str);")
  lines.add("  const ptr = _exports.nimts_alloc(encoded.length + 1);")
  lines.add("  new Uint8Array(_getBuffer(), ptr, encoded.length).set(encoded);")
  lines.add("  return { ptr, len: encoded.length };")
  lines.add("}")
  lines.add("")
  lines.add("function _allocBytes(bytes) {")
  lines.add("  const b = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);")
  lines.add("  const ptr = _exports.nimts_alloc(b.length);")
  lines.add("  new Uint8Array(_getBuffer(), ptr, b.length).set(b);")
  lines.add("  return { ptr, len: b.length };")
  lines.add("}")
  lines.add("")
  lines.add("function _free(ptr) {")
  lines.add("  if (ptr && _exports.nimts_free) _exports.nimts_free(ptr);")
  lines.add("}")
  lines.add("")
  lines.add("function _unpackResult64(packed) {")
  lines.add("  if (typeof packed === 'bigint') {")
  lines.add("    return { ptr: Number(packed & 0xffffffffn), len: Number(packed >> 32n) };")
  lines.add("  }")
  lines.add("  const ptr = _exports.nimts_get_last_result_ptr();")
  lines.add("  const len = _exports.nimts_get_last_result_len();")
  lines.add("  return { ptr, len };")
  lines.add("}")
  lines.add("")
  lines.add("function _readPrimitive(bufOrPtr, len, kind) {")
  lines.add("  let view;")
  lines.add("  if (typeof bufOrPtr === 'number') {")
  lines.add("    if (!bufOrPtr || len <= 0) return kind === 'bool' ? false : (kind === 'int64' ? 0n : 0);")
  lines.add("    view = new DataView(_getBuffer(), bufOrPtr, len);")
  lines.add("  } else if (bufOrPtr instanceof Uint8Array) {")
  lines.add("    if (bufOrPtr.length === 0) return kind === 'bool' ? false : (kind === 'int64' ? 0n : 0);")
  lines.add("    view = new DataView(bufOrPtr.buffer, bufOrPtr.byteOffset, bufOrPtr.byteLength);")
  lines.add("  } else {")
  lines.add("    return kind === 'bool' ? false : (kind === 'int64' ? 0n : 0);")
  lines.add("  }")
  lines.add("  switch (kind) {")
  lines.add("    case 'bool':")
  lines.add("      return view.byteLength >= 4 ? view.getInt32(0, true) !== 0 : view.getInt8(0) !== 0;")
  lines.add("    case 'int32':")
  lines.add("    case 'primitive':")
  lines.add("      if (view.byteLength < 4 && view.byteLength >= 2) return view.getInt16(0, true);")
  lines.add("      if (view.byteLength < 2 && view.byteLength >= 1) return view.getInt8(0);")
  lines.add("      if (view.byteLength < 1) throw new RangeError('Incomplete buffer for type ' + kind + ' (expected at least 1 byte, received ' + view.byteLength + ')');")
  lines.add("      return view.getInt32(0, true);")
  lines.add("    case 'int64':")
  lines.add("      if (view.byteLength < 8) throw new RangeError('Incomplete buffer for type int64 (expected 8 bytes, received ' + view.byteLength + ')');")
  lines.add("      return view.getBigInt64(0, true);")
  lines.add("    case 'float32':")
  lines.add("      if (view.byteLength < 4) throw new RangeError('Incomplete buffer for type float32 (expected 4 bytes, received ' + view.byteLength + ')');")
  lines.add("      return view.getFloat32(0, true);")
  lines.add("    case 'float64':")
  lines.add("      if (view.byteLength < 8) throw new RangeError('Incomplete buffer for type float64 (expected 8 bytes, received ' + view.byteLength + ')');")
  lines.add("      return view.getFloat64(0, true);")
  lines.add("    default:")
  lines.add("      return view.byteLength >= 4 ? view.getInt32(0, true) : 0;")
  lines.add("  }")
  lines.add("}")
  lines.add("")
  lines.add("function _resolveValue(ptrOrBuf, len, kind) {")
  lines.add("  if (kind === 'void') return undefined;")
  lines.add("  if (kind === 'string') {")
  lines.add("    if (ptrOrBuf instanceof Uint8Array) return _textDecoder ? _textDecoder.decode(ptrOrBuf) : _utf8Decode(ptrOrBuf);")
  lines.add("    return _readString(ptrOrBuf, len);")
  lines.add("  }")
  lines.add("  if (kind === 'bytes') {")
  lines.add("    if (ptrOrBuf instanceof Uint8Array) return ptrOrBuf;")
  lines.add("    return _readBytes(ptrOrBuf, len);")
  lines.add("  }")
  lines.add("  if (kind === 'object') {")
  lines.add("    const s = (ptrOrBuf instanceof Uint8Array) ? (_textDecoder ? _textDecoder.decode(ptrOrBuf) : _utf8Decode(ptrOrBuf)) : _readString(ptrOrBuf, len);")
  lines.add("    return s ? JSON.parse(s) : null;")
  lines.add("  }")
  lines.add("  return _readPrimitive(ptrOrBuf, len, kind);")
  lines.add("}")
  lines.add("")

  # Emit handle classes
  for typ in meta.types:
    if typ.isHandle:
      lines.add("export class " & typ.name & " {")
      lines.add("  #handleId = 0;")
      lines.add("  constructor(handleId) {")
      lines.add("    this.#handleId = handleId;")
      lines.add("    if (_finalizer && handleId > 0) _finalizer.register(this, handleId, this);")
      lines.add("  }")
      lines.add("  get handleId() { return this.#handleId; }")
      lines.add("  dispose() {")
      lines.add("    if (this.#handleId !== 0) {")
      lines.add("      if (_finalizer) _finalizer.unregister(this);")
      lines.add("      if (_exports && _exports.nimts_destroy_handle) _exports.nimts_destroy_handle(this.#handleId);")
      lines.add("      this.#handleId = 0;")
      lines.add("    }")
      lines.add("  }")
      lines.add("}")
      lines.add("")

  # Emit NimTsIterator class
  lines.add("export class NimTsIterator {")
  lines.add("  #handleId = 0;")
  lines.add("  #kind = 'primitive';")
  lines.add("  #disposed = false;")
  lines.add("  constructor(handleId, kind = 'primitive') {")
  lines.add("    this.#handleId = handleId;")
  lines.add("    this.#kind = kind;")
  lines.add("    if (_finalizer && handleId > 0) _finalizer.register(this, handleId, this);")
  lines.add("  }")
  lines.add("  get handleId() { return this.#handleId; }")
  lines.add("  next() {")
  lines.add("    if (this.#disposed || this.#handleId === 0) {")
  lines.add("      return { value: undefined, done: true };")
