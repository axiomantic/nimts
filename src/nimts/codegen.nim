import std/strutils
import std/sequtils

type
  TsParam* = object
    name*: string
    nimType*: string
    tsType*: string

  TsTypeField* = object
    name*: string
    tsType*: string

  TsProc* = object
    name*: string
    cabiName*: string
    params*: seq[TsParam]
    returnNimType*: string
    returnTsType*: string
    isAsync*: bool
    isHandleReturn*: bool
    returnKind*: string # "void", "primitive", "string", "bytes", "handle", "object", "promise"

  TsType* = object
    name*: string
    isHandle*: bool
    fields*: seq[TsTypeField]

  TsModuleMeta* = object
    name*: string
    wasmFileName*: string
    types*: seq[TsType]
    procs*: seq[TsProc]

proc mapNimTypeToTs*(nimType: string): string =
  let t = nimType.strip
  case t
  of "int", "int32", "int16", "int8", "uint", "uint32", "uint16", "uint8", "float", "float32", "float64", "csize_t":
    return "number"
  of "int64", "uint64":
    return "bigint"
  of "bool":
    return "boolean"
  of "string", "cstring", "char":
    return "string"
  of "seq[byte]", "openArray[byte]", "seq[uint8]", "openArray[uint8]":
    return "Uint8Array"
  of "void", "":
    return "void"
  else:
    if t.startsWith("Future[") and t.endsWith("]"):
      let inner = t[7 .. ^2]
      return "Promise<" & mapNimTypeToTs(inner) & ">"
    if t.startsWith("Option[") and t.endsWith("]"):
      let inner = t[7 .. ^2]
      return mapNimTypeToTs(inner) & " | null"
    if t.startsWith("seq[") and t.endsWith("]"):
      let inner = t[4 .. ^2]
      return mapNimTypeToTs(inner) & "[]"
    if t.startsWith("NimTsHandle[") and t.endsWith("]"):
      let inner = t[12 .. ^2]
      return inner
    return t

proc generateDts*(meta: TsModuleMeta): string =
  var lines: seq[string] = @[]
  lines.add("// " & meta.name & ".d.ts - Generated by nimts (TypeScript / WASM)")
  lines.add("// Do not edit directly.")
  lines.add("")
  lines.add("export interface NimTsOptions {")
  lines.add("  wasmPath?: string | URL;")
  lines.add("  wasmModule?: WebAssembly.Module;")
  lines.add("  wasmBytes?: BufferSource;")
  lines.add("  wasmInstance?: WebAssembly.Instance;")
  lines.add("  imports?: WebAssembly.Imports;")
  lines.add("}")
  lines.add("")

  # Emit handle classes or interfaces
  for typ in meta.types:
    if typ.isHandle:
      lines.add("export declare class " & typ.name & " {")
      lines.add("  readonly handleId: number;")
      lines.add("  constructor(handleId: number);")
      lines.add("  dispose(): void;")
      lines.add("}")
    else:
      lines.add("export interface " & typ.name & " {")
      for f in typ.fields:
        lines.add("  " & f.name & ": " & f.tsType & ";")
      lines.add("}")
    lines.add("")

  # Emit Exports interface
  lines.add("export interface " & meta.name & "Exports {")
  for p in meta.procs:
    let paramSigs = p.params.mapIt(it.name & ": " & it.tsType).join(", ")
    let retSig = if p.isAsync and not p.returnTsType.startsWith("Promise<"):
      "Promise<" & p.returnTsType & ">"
    else:
      p.returnTsType
    lines.add("  " & p.name & "(" & paramSigs & "): " & retSig & ";")
  lines.add("}")
  lines.add("")

  # Lifecycle methods
  lines.add("export declare function initNimTs(options?: NimTsOptions): Promise<" & meta.name & "Exports>;")
  lines.add("export declare function getNimTs(): " & meta.name & "Exports;")
  lines.add("export declare function getNimTsModule(): any;")
  lines.add("export declare function isInitialized(): boolean;")
  lines.add("")

  # Top-level functions
  for p in meta.procs:
    let paramSigs = p.params.mapIt(it.name & ": " & it.tsType).join(", ")
    let retSig = if p.isAsync and not p.returnTsType.startsWith("Promise<"):
      "Promise<" & p.returnTsType & ">"
    else:
      p.returnTsType
    lines.add("export declare function " & p.name & "(" & paramSigs & "): " & retSig & ";")

  result = lines.join("\n") & "\n"

proc generateJs*(meta: TsModuleMeta, relativeWasmPath: string = ""): string =
  let wasmPath = if relativeWasmPath.len > 0: relativeWasmPath else: "./" & meta.wasmFileName
  var lines: seq[string] = @[]
  lines.add("// " & meta.name & ".js - Generated by nimts (TypeScript / WASM)")
  lines.add("// Do not edit directly.")
  lines.add("")
  lines.add("let _runtime = null;")
  lines.add("let _exports = null;")
  lines.add("let _memory = null;")
  lines.add("let _initialized = false;")
  lines.add("const _textDecoder = new TextDecoder('utf-8');")
  lines.add("const _textEncoder = new TextEncoder();")
  lines.add("const _pendingPromises = new Map();")
  lines.add("const _settledEarly = new Map();")
  lines.add("const _finalizer = typeof FinalizationRegistry !== 'undefined' ? new FinalizationRegistry(h => {")
  lines.add("  if (_exports && _exports.nimts_destroy_handle) _exports.nimts_destroy_handle(h);")
  lines.add("}) : null;")
  lines.add("")
  lines.add("function _assertInit() {")
  lines.add("  if (!_initialized) throw new Error(\"nimts module '" & meta.name & "' not initialized. Await initNimTs() first.\");")
  lines.add("}")
  lines.add("")
  lines.add("function _readString(ptr, len) {")
  lines.add("  if (!ptr || len <= 0) return '';")
  lines.add("  return _textDecoder.decode(new Uint8Array(_memory.buffer, ptr, len));")
  lines.add("}")
  lines.add("")
  lines.add("function _readBytes(ptr, len) {")
  lines.add("  if (!ptr || len <= 0) return new Uint8Array(0);")
  lines.add("  return new Uint8Array(_memory.buffer, ptr, len).slice();")
  lines.add("}")
  lines.add("")
  lines.add("function _allocString(str) {")
  lines.add("  if (typeof str !== 'string') str = String(str);")
  lines.add("  const encoded = _textEncoder.encode(str);")
  lines.add("  const ptr = _exports.nimts_alloc(encoded.length + 1);")
  lines.add("  new Uint8Array(_memory.buffer, ptr, encoded.length).set(encoded);")
  lines.add("  return { ptr, len: encoded.length };")
  lines.add("}")
  lines.add("")
  lines.add("function _allocBytes(bytes) {")
  lines.add("  const b = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);")
  lines.add("  const ptr = _exports.nimts_alloc(b.length);")
  lines.add("  new Uint8Array(_memory.buffer, ptr, b.length).set(b);")
  lines.add("  return { ptr, len: b.length };")
  lines.add("}")
  lines.add("")
  lines.add("function _free(ptr) {")
  lines.add("  if (ptr && _exports.nimts_free) _exports.nimts_free(ptr);")
  lines.add("}")
  lines.add("")
  lines.add("function _unpackResult64(packed) {")
  lines.add("  if (typeof packed === 'bigint') {")
  lines.add("    return { ptr: Number(packed & 0xffffffffn), len: Number(packed >> 32n) };")
  lines.add("  }")
  lines.add("  const ptr = _exports.nimts_get_last_result_ptr();")
  lines.add("  const len = _exports.nimts_get_last_result_len();")
  lines.add("  return { ptr, len };")
  lines.add("}")
  lines.add("")

  # Emit handle classes
  for typ in meta.types:
    if typ.isHandle:
      lines.add("export class " & typ.name & " {")
      lines.add("  #handleId = 0;")
      lines.add("  constructor(handleId) {")
      lines.add("    this.#handleId = handleId;")
      lines.add("    if (_finalizer && handleId > 0) _finalizer.register(this, handleId, this);")
      lines.add("  }")
      lines.add("  get handleId() { return this.#handleId; }")
      lines.add("  dispose() {")
      lines.add("    if (this.#handleId !== 0) {")
      lines.add("      if (_finalizer) _finalizer.unregister(this);")
      lines.add("      if (_exports && _exports.nimts_destroy_handle) _exports.nimts_destroy_handle(this.#handleId);")
      lines.add("      this.#handleId = 0;")
      lines.add("    }")
      lines.add("  }")
      lines.add("}")
      lines.add("")

  # Emit procs
  for p in meta.procs:
    let paramNames = p.params.mapIt(it.name).join(", ")
    lines.add("export " & (if p.isAsync: "async " else: "") & "function " & p.name & "(" & paramNames & ") {")
    lines.add("  _assertInit();")

    var callArgs: seq[string] = @[]
    var allocStmts: seq[string] = @[]
    var freeStmts: seq[string] = @[]

    for param in p.params:
      case param.tsType
      of "string":
        let varName = "_" & param.name & "_buf"
        allocStmts.add("  const " & varName & " = _allocString(" & param.name & ");")
        callArgs.add(varName & ".ptr")
        callArgs.add(varName & ".len")
        freeStmts.add("  _free(" & varName & ".ptr);")
      of "Uint8Array":
        let varName = "_" & param.name & "_buf"
        allocStmts.add("  const " & varName & " = _allocBytes(" & param.name & ");")
        callArgs.add(varName & ".ptr")
        callArgs.add(varName & ".len")
        freeStmts.add("  _free(" & varName & ".ptr);")
      of "number", "boolean":
        callArgs.add(param.name)
      else:
        if param.nimType.contains("Handle") or meta.types.anyIt(it.name == param.tsType and it.isHandle):
          callArgs.add(param.name & ".handleId")
        else:
          let varName = "_" & param.name & "_buf"
          allocStmts.add("  const " & varName & " = _allocString(JSON.stringify(" & param.name & "));")
          callArgs.add(varName & ".ptr")
          callArgs.add(varName & ".len")
          freeStmts.add("  _free(" & varName & ".ptr);")

    for a in allocStmts: lines.add(a)
    lines.add("  try {")
    let rawCall = "_exports." & p.cabiName & "(" & callArgs.join(", ") & ")"

    if p.isAsync:
      lines.add("    const promiseId = " & rawCall & ";")
      lines.add("    return new Promise((resolve, reject) => {")
      lines.add("      if (_settledEarly.has(promiseId)) {")
      lines.add("        const early = _settledEarly.get(promiseId);")
      lines.add("        _settledEarly.delete(promiseId);")
      lines.add("        if (early.isError) reject(new Error(early.strVal));")
      lines.add("        else {")
      if p.returnKind == "string":
        lines.add("          resolve(early.strVal);")
      elif p.returnKind == "bytes":
        lines.add("          resolve(early.bytesVal);")
      elif p.returnKind == "object":
        lines.add("          resolve(JSON.parse(early.strVal));")
      elif p.returnKind == "primitive":
        lines.add("          resolve(early.primitiveVal);")
      else:
        lines.add("          resolve(early.strVal);")
      lines.add("        }")
      lines.add("      } else {")
      lines.add("        _pendingPromises.set(promiseId, { resolve, reject, kind: " & "\"" & p.returnKind & "\"" & " });")
      lines.add("      }")
      lines.add("    });")
    else:
      case p.returnKind
      of "void":
        lines.add("    " & rawCall & ";")
        lines.add("    return;")
      of "primitive":
        if p.returnTsType == "boolean":
          lines.add("    return Boolean(" & rawCall & ");")
        else:
          lines.add("    return " & rawCall & ";")
      of "string":
        lines.add("    const packed = " & rawCall & ";")
        lines.add("    const { ptr, len } = _unpackResult64(packed);")
        lines.add("    const str = _readString(ptr, len);")
        lines.add("    _free(ptr);")
        lines.add("    return str;")
      of "bytes":
        lines.add("    const packed = " & rawCall & ";")
        lines.add("    const { ptr, len } = _unpackResult64(packed);")
        lines.add("    const bytes = _readBytes(ptr, len);")
        lines.add("    _free(ptr);")
        lines.add("    return bytes;")
      of "handle":
        lines.add("    const handleId = " & rawCall & ";")
        lines.add("    return new " & p.returnTsType & "(handleId);")
      of "object":
        lines.add("    const packed = " & rawCall & ";")
        lines.add("    const { ptr, len } = _unpackResult64(packed);")
        lines.add("    const jsonStr = _readString(ptr, len);")
        lines.add("    _free(ptr);")
        lines.add("    return JSON.parse(jsonStr);")
      else:
        lines.add("    return " & rawCall & ";")

    lines.add("  } finally {")
    for f in freeStmts: lines.add(f)
    lines.add("  }")
    lines.add("}")
    lines.add("")

  # Exports dictionary
  lines.add("const _exportsObj = {")
  for p in meta.procs:
    lines.add("  " & p.name & ",")
  lines.add("};")
  lines.add("")

  # initNimTs with Gotcha 1 solution (instantiateStreaming + fallback)
  lines.add("export async function initNimTs(options = {}) {")
  lines.add("  if (_initialized) return _exportsObj;")
  lines.add("  const wasmTarget = options.wasmPath || " & "\"" & wasmPath & "\";")
  lines.add("  const importObject = {")
  lines.add("    env: {")
  lines.add("      nimts_js_resolve_promise: (promiseId, ptr, len) => {")
  lines.add("        const p = _pendingPromises.get(promiseId);")
  lines.add("        if (p) {")
  lines.add("          _pendingPromises.delete(promiseId);")
  lines.add("          let res = null;")
  lines.add("          if (p.kind === 'string') res = _readString(ptr, len);")
  lines.add("          else if (p.kind === 'bytes') res = _readBytes(ptr, len);")
  lines.add("          else if (p.kind === 'object') res = JSON.parse(_readString(ptr, len));")
  lines.add("          else if (p.kind === 'primitive') res = new Int32Array(_memory.buffer, ptr, 1)[0];")
  lines.add("          else res = _readString(ptr, len);")
  lines.add("          p.resolve(res);")
  lines.add("        } else {")
  lines.add("          const strVal = _readString(ptr, len);")
  lines.add("          const primitiveVal = ptr && len >= 4 ? new Int32Array(_memory.buffer, ptr, 1)[0] : 0;")
  lines.add("          const bytesVal = _readBytes(ptr, len);")
  lines.add("          _settledEarly.set(promiseId, { isError: false, strVal, primitiveVal, bytesVal });")
  lines.add("        }")
  lines.add("      },")
  lines.add("      nimts_js_reject_promise: (promiseId, ptr, len) => {")
  lines.add("        const p = _pendingPromises.get(promiseId);")
  lines.add("        const strVal = _readString(ptr, len);")
  lines.add("        if (p) {")
  lines.add("          _pendingPromises.delete(promiseId);")
  lines.add("          p.reject(new Error(strVal));")
  lines.add("        } else {")
  lines.add("          _settledEarly.set(promiseId, { isError: true, strVal });")
  lines.add("        }")
  lines.add("      },")
  lines.add("      nimts_js_call_async: (funcId, futureId, ptr, len) => {")
  lines.add("        if (options.imports?.env?.nimts_js_call_async) {")
  lines.add("          options.imports.env.nimts_js_call_async(funcId, futureId, ptr, len);")
  lines.add("        }")
  lines.add("      }")
  lines.add("    },")
  lines.add("    wasi_snapshot_preview1: new Proxy({}, { get: () => () => 0 }),")
  lines.add("    ...(options.imports || {})")
  lines.add("  };")
  lines.add("")
  lines.add("  let instance = null;")
  lines.add("  if (options.wasmInstance) {")
  lines.add("    instance = options.wasmInstance;")
  lines.add("  } else if (options.wasmModule) {")
  lines.add("    instance = await WebAssembly.instantiate(options.wasmModule, importObject);")
  lines.add("  } else if (options.wasmBytes) {")
  lines.add("    const res = await WebAssembly.instantiate(options.wasmBytes, importObject);")
  lines.add("    instance = res.instance;")
  lines.add("  } else if (typeof WebAssembly.instantiateStreaming === 'function' && typeof fetch !== 'undefined') {")
  lines.add("    try {")
  lines.add("      const resp = await fetch(wasmTarget);")
  lines.add("      if (resp && resp.ok) {")
  lines.add("        const res = await WebAssembly.instantiateStreaming(resp, importObject);")
  lines.add("        instance = res.instance;")
  lines.add("      }")
  lines.add("    } catch (_) {}")
  lines.add("  }")
  lines.add("")
  lines.add("  if (!instance) {")
  lines.add("    let bytes = null;")
  lines.add("    if (typeof process !== 'undefined' && process.versions?.node) {")
  lines.add("      const fs = await import('node:fs/promises');")
  lines.add("      bytes = await fs.readFile(wasmTarget);")
  lines.add("    } else {")
  lines.add("      const resp = await fetch(wasmTarget);")
  lines.add("      bytes = await resp.arrayBuffer();")
  lines.add("    }")
  lines.add("    const res = await WebAssembly.instantiate(bytes, importObject);")
  lines.add("    instance = res.instance;")
  lines.add("  }")
  lines.add("")
  lines.add("  _exports = instance.exports;")
  lines.add("  _memory = _exports.memory;")
  lines.add("  _initialized = true;")
  lines.add("  return _exportsObj;")
  lines.add("}")
  lines.add("")
  lines.add("export function getNimTs() {")
  lines.add("  _assertInit();")
  lines.add("  return _exportsObj;")
  lines.add("}")
  lines.add("")
  lines.add("export function getNimTsModule() {")
  lines.add("  _assertInit();")
  lines.add("  return _exports;")
  lines.add("}")
  lines.add("")
  lines.add("export function isInitialized() {")
  lines.add("  return _initialized;")
  lines.add("}")
  lines.add("")

  result = lines.join("\n") & "\n"
